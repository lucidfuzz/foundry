#!/usr/bin/env python3
"""Make the served copies of each theme's artwork. Run after adding or changing art:  python3 scripts/art.py

Originals in assets/<theme>/*.png are never modified. For each theme this writes:
  assets/<theme>/web/<sheet>.webp     full resolution, compressed, for the website
  assets/<theme>/thumb/<sheet>.webp   small, for the theme picker card (loads first, so the page stays fast)
  assets/<theme>/widget/<sprite>.png  each widget crop sized for the largest widget that draws it (WIDGET_PX), downloaded once by the iPhone script
and src/art-manifest.js, listing every file with a content hash so browsers and phones refresh changed art.
Needs Python 3 with Pillow.
"""
import argparse, hashlib, json, os, re
from fractions import Fraction
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# theme -> (source file holding its sprite table, name of the table)
THEMES = {'halcyon': ('src/halcyon/paint.js', 'HB_SPRITES'), 'rabbit': ('src/paint/97_rabbit_afterimage.js', 'WR_SPRITES'), 'longroad': ('src/paint/97_longroad_folio.js', 'LRF_SPRITES')}
WIDGET_MAX, THUMB_MAX = 480, 360
# Long edge in pixels for each widget crop: 3x (iPhone screen density) the largest size that crop is drawn at in any
# widget, measured across all 12 widgets in all 3 sizes, rounded up. Never larger than the original art allows.
# Each widget only downloads the few crops it draws, so the phone's widget memory stays comfortable.
WIDGET_PX = {**{'mark%02d' % i: 288 for i in range(1,13)}, 'compass':306, **{'journey%02d' % i: 609 for i in range(1,9)}, 'hourglass': 324, 'sundial': 372, 'letters': 288, 'crier': 210, 'minstrel': 420, 'tavern': 978,
             **{'stage%02d' % i: 1002 for i in range(1,13)},
             **{'place%02d' % i: 1020 for i in range(1,7)},
             **{'terrain%02d' % i: 990 for i in range(1,7)},'signal': 912, 'optical': 672, 'archive': 688, 'collective': 672, 'lungsDetail': 608, 'heartDetail': 544,
             'neural': 512, 'heart': 544, 'lungs': 608, 'saturn': 432, 'neptune': 432, 'jupiter': 432, 'knot': 432,
             'membrane': 432, 'loops': 432, 'tissue': 192, 'mask': 750, 'vault': 390, 'edge': 387, 'audio': 399, 'warren': 474, 'cover': 594, 'invite': 513,
             **{'lot%02d' % i: 540 for i in range(1, 13)}}

def sprites(src, name):
    body = re.search(r'const %s\s*=\s*\{(.*?)\n\};' % name, open(os.path.join(ROOT, src)).read(), re.S).group(1)
    num = lambda t: float(Fraction(t.strip())) if '/' in t else float(t)
    return {k: (sheet, *map(num, rest.split(','))) for k, sheet, rest in re.findall(r"(\w+)\s*:\s*\[\s*'([\w-]+)'\s*,([^\]]+)\]", body)}

def tag(path): return hashlib.sha256(open(path, 'rb').read()).hexdigest()[:10]
def rel(path): return os.path.relpath(path, ROOT).replace(os.sep, '/')

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--theme', choices=THEMES, help='Build only this theme and preserve the other manifest entries.')
args = parser.parse_args()
manifest = {}
if args.theme:
    manifest_file = os.path.join(ROOT, 'src', 'art-manifest.js')
    if os.path.exists(manifest_file):
        with open(manifest_file) as f:
            manifest = json.loads(f.read().split('const ART_MANIFEST = ', 1)[1].strip().removesuffix(';'))
for theme, (src, table) in THEMES.items():
    if args.theme and theme != args.theme: continue
    base = os.path.join(ROOT, 'assets', theme)
    for d in ('web', 'thumb', 'widget'): os.makedirs(os.path.join(base, d), exist_ok=True)
    entry = {'sheets': {}, 'thumbs': {}, 'widget': {}}
    active_sheets = {spec[0] for spec in sprites(src, table).values()}
    originals = {f[:-4]: Image.open(os.path.join(base, f)).convert('RGBA') for f in sorted(os.listdir(base)) if f.endswith('.png') and (theme != 'longroad' or f[:-4] in active_sheets)}
    for name, im in originals.items():
        web = os.path.join(base, 'web', name + '.webp'); im.save(web, 'WEBP', quality=88, method=6)
        th = im.copy(); th.thumbnail((THUMB_MAX, THUMB_MAX), Image.LANCZOS); thumb = os.path.join(base, 'thumb', name + '.webp'); th.save(thumb, "WEBP", quality=74, method=6)
        entry['sheets'][name] = f'{rel(web)}?v={tag(web)}'; entry['thumbs'][name] = f'{rel(thumb)}?v={tag(thumb)}'
    for key, (sheet, x, y, w, h) in sprites(src, table).items():
        im = originals[sheet]; W, H = im.size
        crop = im.crop((round(W * x), round(H * y), round(W * (x + w)), round(H * (y + h))))
        px = WIDGET_PX.get(key, WIDGET_MAX); crop.thumbnail((px, px), Image.LANCZOS)
        out = os.path.join(base, 'widget', key + '.png'); crop.save(out, 'PNG', optimize=True)
        entry['widget'][key] = f'{rel(out)}?v={tag(out)}'
    manifest[theme] = entry
with open(os.path.join(ROOT, 'src', 'art-manifest.js'), 'w') as f:
    f.write('// Generated by scripts/art.py. Served copies of each theme\'s artwork, with content hashes.\nconst ART_MANIFEST = ' + json.dumps(manifest, indent=1) + ';\n')
for theme, e in manifest.items():
    size = lambda grp: sum(os.path.getsize(os.path.join(ROOT, u.split('?')[0])) for u in e[grp].values())
    print(f"{theme}: web {size('sheets')/1e6:.2f} MB, thumbs {size('thumbs')/1e3:.0f} KB, widget crops {size('widget')/1e6:.2f} MB ({len(e['widget'])} files)")
